def render_page(p: dict) -> str:
    html = page_template.replace("{{ header_html }}", render_header(""))
    html = html.replace("{{ page_title }}", p["page_title"])
    html = html.replace("{{ meta_description }}", p["meta_description"])
    html = html.replace("{{ canonical_url }}", p["canonical_url"])
    html = html.replace("{{ breadcrumb_section }}", p["breadcrumb_section"])
    html = html.replace("{{ eyebrow }}", p["eyebrow"])
    html = html.replace("{{ h1_title }}", p["h1_title"])
    html = html.replace("{{ summary }}", p["summary"])
    html = html.replace("{{ content_body }}", p["content_body"])
    html = html.replace("{{ footer_html }}", footer_html)
    return html


def build_all():
    print(f"Building {len(PAGES)} Stockerboard Trust Pages...")
    for p in PAGES:
        target_dir = ROOT / p["dir_name"]
        target_dir.mkdir(parents=True, exist_ok=True)
        target_file = target_dir / "index.html"
        rendered = render_page(p)
        target_file.write_text(rendered, encoding="utf-8")
        print(f" -> Generated: {target_file.relative_to(ROOT)} ({len(rendered):,} bytes)")
    print("All trust pages generated successfully.")


